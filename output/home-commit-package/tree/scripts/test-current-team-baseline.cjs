'use strict';
const fs = require('node:fs'), assert = require('node:assert/strict');
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const { currentTeamVolume, withDisciplineHistory } = require('./predictions/current-sot-volume.cjs');
const matches = read('data/normalized/matches.json');
const historicalProfiles = withDisciplineHistory(read('data/normalized/team-volume-profiles-2025-26.json').profiles, read('data/normalized/referee-matches/2025-26/serie-a.json').matches);
const targetMatch = matches.find(m => m.id === 'cagliari-frosinone-2026-27-md-11');
const p = currentTeamVolume({ matches, historicalProfiles, teamId: 'frosinone', targetMatch });
for (const metric of ['totalShots', 'shotsOnTarget', 'wonCorners', 'fouls', 'yellowCards']) {
  assert.equal(p.currentVolumeBaseline[metric].ownMatches, 10);
  assert(Number.isFinite(p.venues.away[metric].for.mean));
}
const { applyOwnOffensiveVolumeProfile, applyOpponentTeamVolumeInteraction } = require('./predictions/engine');
const metrics = [{ central: 18, min: 12, max: 24 }, { central: 6, min: 3, max: 9 }, { central: 6, min: 3, max: 9 }];
const previous = structuredClone(metrics);
applyOwnOffensiveVolumeProfile({ offense: { teamOffensiveAllocation: { enabled: true, teamShotMaxAdjustmentPct: 6, teamSotMaxAdjustmentPct: 6, cornerMaxAdjustmentPct: 4 }, teamShotVolume: { shrunkPerGame: 30 }, teamSotVolume: { shrunkPerGame: 10 }, teamSetPieceOpportunityVolume: { shrunkCornersPerGame: 12 } } }, ...metrics, { totalShots: true, shotsOnTarget: true, wonCorners: true });
assert.deepEqual(metrics, previous, 'Current team bases must not get a second own-volume adjustment');
const { currentGoalInputs } = require('./predictions/current-goal-inputs.cjs');
const historicalMatches = read('data/normalized/referee-matches/2025-26/serie-a.json').matches;
const styles = read('data/normalized/team-style-profiles.json').profiles;
const makeGoals = input => currentGoalInputs({ matches: input, historicalMatches, teamId: 'frosinone', targetMatch, profile: styles.find(p => p.teamId === 'frosinone'), historicalXg: null, xgLeagueSummary: { homeXgPerMatch: 1.5, awayXgPerMatch: 1.2 } });
const goals = makeGoals(matches);
assert.equal(goals.diagnostics.sampleSize, 10);
assert.equal(goals.diagnostics.priorEquivalentMatches, 4);
assert.equal(goals.profile.goalRatesOnTargetScale, true);
assert.equal(goals.xg.currentXgCoverage.for, 10);
const future = structuredClone(matches);
const next = future.find(m => m.id === targetMatch.id);
next.status = 'finished'; next.score = { home: 999, away: 999 }; next.teamStats = { home: { expectedGoals: 999, shots: 999, corners: 999, fouls: 999, yellowCards: 999 }, away: { expectedGoals: 999, shots: 999, corners: 999, fouls: 999, yellowCards: 999 } };
assert.deepEqual(makeGoals(future), goals);
assert.deepEqual(currentTeamVolume({ matches: future, historicalProfiles, teamId: 'frosinone', targetMatch }), p);
const changed = structuredClone(matches);
const recentMatch = changed.find(m => m.id === 'frosinone-torino-2026-27-md-10');
recentMatch.score.home += 2; recentMatch.teamStats.home.expectedGoals += 1;
const changedGoals = makeGoals(changed);
assert(changedGoals.profile.currentGoalRates.for > goals.profile.currentGoalRates.for);
assert(changedGoals.xg.overall.for > goals.xg.overall.for);
for (const m of changed) if (m.homeTeam === 'frosinone') delete m.teamStats?.home?.expectedGoals;
assert(makeGoals(changed).xg.currentXgCoverage.for < 10, 'Missing xG must not become observed zero');
console.log('OK five current volume baselines, ten fixtures, no duplicate team adjustment.');
