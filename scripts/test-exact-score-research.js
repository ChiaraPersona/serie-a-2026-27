"use strict";
const assert = require("assert"), fs = require("fs"), path = require("path");
const D = require("./research/exact-score/distribution");
const E = require("./research/exact-score/evaluate");
const C = require("./research/exact-score/contracts");
const M = require("./research/exact-score/models");
const F = require("./research/exact-score/features");

function runSyntheticTests() {
  let assertions = 0;
  const check = (condition, message) => { assert(condition, message); assertions++; };
  const near = (actual, expected, tolerance = 1e-9) => check(Math.abs(actual - expected) <= tolerance, `${actual} != ${expected}`);
  const throws = fn => { assert.throws(fn); assertions++; };
  for (const [home, away] of [[0, 0], [0, 1.4], [0.1, 0.2], [1, 1], [1.4, 1.1], [4, 0.5], [6, 7], [30, 25], [100, 90]]) {
    const matrix = D.independentPoissonScoreMatrix(home, away);
    check(D.validateMatrix(matrix).valid, "matrix validation");
    check(matrix.maxHomeGoals >= 6 && matrix.maxAwayGoals >= 6, "minimum 0..6 support");
    check(matrix.tailBound <= 1e-12, "tail bound controlled");
    near(matrix.cells.flat().reduce((a, b) => a + b, 0), 1);
    check(matrix.cells.flat().every(p => p >= 0 && p <= 1), "bounded probabilities");
    const markets = D.deriveMarkets(matrix);
    near(markets.outcomes.home + markets.outcomes.draw + markets.outcomes.away, 1);
    near(markets.btts.yes + markets.btts.no, 1);
    near(markets.btts.yes, (1 - Math.exp(-home)) * (1 - Math.exp(-away)));
    near(D.scoreProbability(matrix, 0, 0), Math.exp(-home - away));
    for (const line of [0.5, 1.5, 2.5, 3.5, 4.5]) near(markets.overUnder[line].over + markets.overUnder[line].under, 1);
    check([0.5, 1.5, 2.5, 3.5].every(line => markets.overUnder[line].over >= markets.overUnder[line + 1].over), "O/U monotonicity");
    const info = D.distributionDiagnostics(matrix);
    check(info.top3.length === 3 && info.top5.length === 5, "top N cardinality");
    check(info.top3ProbabilityMass <= info.top5ProbabilityMass && info.top5ProbabilityMass <= 1 + 1e-12, "top mass ordering");
    const third = info.top3[2];
    check(D.actualScoreRank(matrix, third.homeGoals, third.awayGoals) === 3, "actual rank");
    near(D.scoreProbability(matrix, third.homeGoals, third.awayGoals), third.probability);
    check(Number.isFinite(info.entropy) && info.entropy >= 0 && info.modelConfidence === null, "entropy separate from confidence");
  }
  const symmetric = D.independentPoissonScoreMatrix(1.3, 1.3);
  symmetric.cells.forEach((row, h) => row.forEach((p, a) => near(p, symmetric.cells[a][h])));
  const dominant = D.deriveMarkets(D.independentPoissonScoreMatrix(4.2, 0.4));
  check(dominant.outcomes.home > dominant.outcomes.away, "home lambda dominance");
  check(D.distributionDiagnostics(D.independentPoissonScoreMatrix(0.05, 0.1)).modalScore === "0-0", "low lambda modal");
  check(D.distributionDiagnostics(D.independentPoissonScoreMatrix(6.3, 5.4)).modalScore === "6-5", "high lambda mass shift");
  throws(() => D.independentPoissonScoreMatrix(-1, 1));
  throws(() => D.independentPoissonScoreMatrix(NaN, 1));
  throws(() => D.independentPoissonScoreMatrix(Infinity, 1));
  throws(() => D.independentPoissonScoreMatrix(5, 5, { maxGoalsLimit: 6 }));
  throws(() => D.independentPoissonScoreMatrix(1000, 1));
  throws(() => D.validateMatrix({ cells: [[-0.1, 1.1]] }));
  throws(() => D.validateMatrix({ cells: [[0.5]] }));
  throws(() => D.topScores(symmetric, 0));
  throws(() => D.scoreProbability(symmetric, null, 0));
  throws(() => D.deriveMarkets(symmetric, [2]));
  const matrix = D.independentPoissonScoreMatrix(1.4, 0.9), saved = JSON.stringify(matrix);
  const outside = D.scoreProbability(matrix, 40, 1);
  check(outside > 0 && outside < 1e-15, "analytic exact tail probability");
  check(D.actualScoreRank(matrix, 40, 1) === null, "rank outside support explicitly unavailable");
  near(E.logLoss(0.2), -Math.log(0.2));
  near(E.scoreSurprise(0.2), -Math.log(0.2));
  check(Number.isFinite(E.logLoss(0)), "epsilon evaluation only");
  check(JSON.stringify(matrix) === saved, "evaluation never alters prediction");
  near(E.rankedProbabilityScore([1, 0, 0], 0), 0);
  near(E.rankedProbabilityScore([0, 0, 1], 0), 1);
  near(E.rankedProbabilityScore([0, 1, 0], 0), 0.5);
  near(E.rankedProbabilityScore([1 / 3, 1 / 3, 1 / 3], 1), 1 / 9);
  throws(() => E.rankedProbabilityScore([0.1, 0.1, 0.1], 0));
  near(E.binaryMetrics([{ p: 0.8, y: 1 }, { p: 0.2, y: 0 }]).brier, 0.04);
  near(E.continuousMetrics([{ p: 2, y: 1 }, { p: 1, y: 3 }]).mae, 1.5);
  near(E.continuousMetrics([{ p: 2, y: 1 }, { p: 1, y: 3 }]).rmse, Math.sqrt(2.5));
  check(E.binaryMetrics([]).brier === null, "empty metrics N/D");
  near(E.calibration([{ p: 1, y: 1 }, { p: 0, y: 0 }]).ece, 0);

  const target = { id: "h-a-md2", competition: "serie-a", season: "2026-27", homeTeam: "h", awayTeam: "a", date: "2026-08-30", kickoff: "15:00", timezone: "Europe/Rome", matchday: 2, status: "finished", score: { home: 9, away: 9 } };
  const past = { ...target, id: "h-a-md1", date: "2026-08-23", matchday: 1, score: { home: 1, away: 0 }, teamStats: { home: { expectedGoals: 0.8, shots: 10, shotsOnTarget: 0 }, away: { expectedGoals: null, shots: 8 } } };
  const future = { ...target, id: "h-a-md3", date: "2026-09-05", matchday: 3, score: { home: 99, away: 99 } };
  const sourceHashes = { "data/normalized/matches.json": "synthetic-current", "data/normalized/standings-2025-26.json": "synthetic-historical" };
  const prior = { competition: "serie-a", season: "2025-26", status: "final", retrievedAt: "2026-07-18", rows: [{ team: "h", played: 38, goalsFor: 38, goalsAgainst: 38 }], homeRows: [{ team: "h", played: 19, goalsFor: 30, goalsAgainst: 20 }], awayRows: [{ team: "h", played: 19, goalsFor: 20, goalsAgainst: 30 }] };
  const matches = [past, target, future];
  const vector = F.makeFeatureVector({ target, matches, prior, sourceHashes });
  near(vector.features["home.goalsFor"].value, 1);
  near(vector.features["home.baselineSOT"].value, 0);
  check(vector.features["away.currentXGF"].value === null, "missing xG != zero");
  check(vector.features["home.predictedTeamShots"].value === null, "no retrospective V2 inference");
  check(vector.features["home.goalsFor"].provenance.matchesUsed.join() === past.id, "strict target/future exclusion");
  check(C.validateFeatureVector(vector, matches), "feature contract provenance");
  const ablated = C.ablateFeatureGroups(vector, ["GOAL_HISTORY", "HOME_AWAY", "MATURITY"]);
  check(ablated.features["home.currentXGF"].value === null && vector.features["home.currentXGF"].value === 0.8 && ablated.features["home.goalsFor"].value === 1, "ablation masks groups without altering common input");
  check(C.validateFeatureVector(ablated, matches), "ablated contract retains cutoff/provenance");
  throws(() => C.ablateFeatureGroups(vector, ["UNKNOWN"]));
  const wrongIdentity = structuredClone(vector); wrongIdentity.homeTeam = "other";
  throws(() => C.validateFeatureVector(wrongIdentity, matches));
  const wrongClass = structuredClone(vector); wrongClass.retrospective = false;
  throws(() => C.validateFeatureVector(wrongClass, matches));
  const badTimestamp = structuredClone(vector); badTimestamp.features["home.goalsFor"].provenance.availableBefore = "unparseable";
  throws(() => C.validateFeatureVector(badTimestamp, matches));
  const leaked = structuredClone(vector); leaked.features["home.goalsFor"].provenance.matchesUsed.push(target.id);
  throws(() => C.validateFeatureVector(leaked, matches));
  const futureLeaked = structuredClone(vector); futureLeaked.features["home.goalsFor"].provenance.matchesUsed.push(future.id);
  throws(() => C.validateFeatureVector(futureLeaked, matches));
  const tampered = structuredClone(vector); tampered.dataCutoff.matchdayExclusive = 3;
  throws(() => C.validateFeatureVector(tampered, matches));
  const badPrior = F.makeFeatureVector({ target, matches, prior: { ...prior, competition: "serie-b" }, sourceHashes });
  check(badPrior.features["home.historicalGoalsFor"].value === null, "Serie B never equivalent");
  const latePrior = F.makeFeatureVector({ target, matches, prior: { ...prior, retrievedAt: "2026-09-01" }, sourceHashes });
  check(latePrior.features["home.historicalGoalsFor"].value === null, "late historical source prohibited");
  const changedTargets = matches.map(m => m.matchday >= 2 ? { ...m, score: { home: 1000, away: 500 }, teamStats: { home: { expectedGoals: 500 } } } : m);
  check(JSON.stringify(F.makeFeatureVector({ target: changedTargets[1], matches: changedTargets, prior, sourceHashes }).features) === JSON.stringify(vector.features), "features invariant to target/future actuals");
  const postponedPriorRound = { ...past, date: "2026-09-01" };
  check(F.makeFeatureVector({ target, matches: [postponedPriorRound, target], prior, sourceHashes }).features["home.currentMatches"].value === 0, "late prior-round result excluded by date");
  const live = { ...past, status: "live" };
  check(F.makeFeatureVector({ target, matches: [live, target], prior, sourceHashes }).features["home.currentMatches"].value === 0, "live rows excluded");
  check(F.actualForResearch({ ...target, matchday: 6 }).actualHomeGoals === null, "MD6 actuals unavailable despite injected result");
  check(F.actualForResearch({ ...target, status: "awarded" }).availability === "UNAVAILABLE", "non-sporting results unavailable");
  const entries = M.registry("2026-10-03T00:00:00Z").models;
  entries.forEach(model => check(model.state === "RESEARCH" && !model.fitted && !model.production, "research-only registry"));
  throws(() => C.assertResearchState({ ...entries[0], state: "SHADOW" }, "INSUFFICIENT"));
  throws(() => C.assertResearchState({ ...entries[0], production: true }, "READY_FOR_BASELINE_MODEL"));
  const league = M.createModel(entries[0]);
  const prediction = league.predictMatch(vector);
  near(prediction.lambdaHome, 1); near(prediction.lambdaAway, 0);
  check(M.createModel(entries[1]).predictMatch(vector) === null, "no invented shrinkage defaults");
  const goals = M.createModel(entries[1], { priorEquivalentMatches: 12 }).predictMatch(vector);
  check(goals === null, "zero league away environment has insufficient strength normalization");
  check(M.createModel(entries[3]).predictMatch(vector) === null, "process interface only");
  throws(() => M.futureDependencyDistribution());
  throws(() => M.shrink(1, 3, 1, 0));
  const row = { matchId: target.id, targetMatchday: 2, generationClass: "RETROSPECTIVE", dataCutoff: vector.dataCutoff, vector, actual: F.actualForResearch({ ...target, score: { home: 1, away: 0 } }) };
  const evaluated = E.evaluateModel([prediction], [row], entries[0]);
  check(evaluated.sample === 1 && evaluated.oneXtwo.rps >= 0 && evaluated.top3Coverage >= 0, "complete synthetic evaluation");
  check(evaluated.matchDiagnostics[0].actualScoreProbability > 0, "actual probability available");
  throws(() => E.evaluateModel([prediction, prediction], [row], entries[0]));
  throws(() => E.evaluateModel([prediction], [row, { ...row, generationClass: "PROSPECTIVE" }], entries[0]));
  throws(() => E.matchDiagnostic(prediction, { ...row, actual: { ...row.actual, actualHomeGoals: null } }));
  const oracle = C.oracleTeamProcess(vector, row.actual, { offline: true });
  check(oracle.predictionEligible === false, "oracle explicitly ineligible");
  throws(() => league.predictMatch(oracle));
  throws(() => C.oracleTeamProcess(vector, row.actual));
  throws(() => C.oracleTeamProcess({ ...vector, generationClass: "PROSPECTIVE" }, row.actual, { offline: true }));
  check(C.assertTrainingBoundary({ matchIds: [past.id], matchdays: [1], firstMD: 1, lastMD: 1, cutoff: "2026-08-24", featureSet: ["GOAL_HISTORY"], objective: "score log loss" }, vector, matches), "valid fit provenance");
  throws(() => C.assertTrainingBoundary({ matchIds: [target.id], matchdays: [2], firstMD: 2, lastMD: 2, cutoff: "2026-08-29", featureSet: ["GOAL_HISTORY"], objective: "score log loss" }, vector, matches));
  const folds = E.walkForwardFolds([{ ...row, matchId: past.id, targetMatchday: 1, actual: F.actualForResearch(past) }, row]);
  check(folds[0].trainingMatchIds.length === 0 && folds[1].trainingMatchIds[0] === past.id && !folds[1].trainingMatchIds.includes(target.id), "opening fold and temporal train/test");
  const lateFolds = E.walkForwardFolds([{ ...row, matchId: past.id, targetMatchday: 1, actual: { ...F.actualForResearch(past), completedBy: "2026-09-01T23:59:59Z" } }, row]);
  check(lateFolds[1].trainingMatchIds.length === 0, "postponed training actuals excluded by completion date");
  const sample = E.commonSample({ m0: [{ matchId: past.id }, prediction], m1: [prediction] }, [{ ...row, matchId: past.id }, row]);
  check(sample.length === 1 && sample[0].matchId === target.id, "same-sample intersection");
  const vectors = Array.from({ length: 35 }, (_, i) => ({ features: { a: { value: i }, b: { value: i * 2 }, missing: { value: null } } }));
  const correlations = E.correlationMatrix(vectors, ["a", "b", "missing"]);
  check(correlations.find(p => p.left === "a" && p.right === "b").highCollinearity, "redundancy flag");
  check(correlations.find(p => p.right === "missing").correlation === null, "pairwise missing filtering");
  const clustered = [{ matchId: "a", matchday: 1, x: 1 }, { matchId: "b", matchday: 1, x: 3 }, { matchId: "c", matchday: 2, x: 4 }];
  const boot = E.clusterBootstrap(clustered, rows => rows.reduce((n, r) => n + r.x, 0) / rows.length, { unit: "MATCHDAY", iterations: 100, minimumClusters: 2 });
  check(boot.clusters === 2 && boot.interval.length === 2, "matchday bootstrap clusters");
  check(E.clusterBootstrap(clustered, () => 1, { unit: "MATCHDAY", iterations: 5, minimumClusters: 3 }).status === "INSUFFICIENT", "bootstrap sample gate");
  return { status: "PASS", assertions, scope: "SYNTHETIC_MATH_TEMPORAL_CONTRACT_EVALUATOR" };
}

function runRepositoryTests() {
  const { loadInputs, buildResearchArtifacts, parseConfiguration } = require("./research/exact-score/run");
  const inputs = loadInputs(), outputs = buildResearchArtifacts(inputs);
  const rows = outputs.retrospectiveDataset.rows;
  assert.equal(rows.length, 50);
  assert.equal(outputs.prospectiveDataset.sample, 10);
  assert.equal(outputs.evaluation.exactScoreDataGate, "INSUFFICIENT");
  assert.equal(outputs.evaluation.modelChangeGate, "CLOSED");
  assert.equal(outputs.evaluation.sameSample.n, 50);
  assert.equal(outputs.evaluation.prospective.metrics, null);
  outputs.prospectiveDataset.rows.forEach(row => { assert.equal(row.actual.actualHomeGoals, null); assert.equal(row.actual.actualAwayGoals, null); assert.equal(row.exactScorePrediction, null); assert.equal(row.generationClass, "PROSPECTIVE"); });
  for (const row of rows) {
    assert.equal(row.generationClass, "RETROSPECTIVE"); C.validateFeatureVector(row.vector, inputs.matches);
    for (const feature of Object.values(row.vector.features)) assert(!feature.provenance.matchesUsed.includes(row.matchId));
  }
  const configured = buildResearchArtifacts(inputs, { priorEquivalentMatches: 12, minimumXGCoverage: 1 });
  const models = configured.evaluation.retrospective.models;
  assert.equal(models.length, 3);
  assert.equal(configured.evaluation.sameSample.n, 28);
  models.forEach(m => assert.deepEqual(m.matchIds, models[0].matchIds));
  assert(models.every(m => m.sample === 28 && m.model.state === "RESEARCH"));
  const md1 = rows.find(row => row.targetMatchday === 1);
  assert.equal(md1.vector.features["league.homeGoalsAverage"].value, null);
  const league = M.createModel(outputs.models.models[0]);
  assert(league.predictMatch(md1.vector).diagnostics.leagueFallbackUsed);
  assert(rows.filter(row => row.targetMatchday === 1).every(row => row.vector.features["home.currentMatches"].value === 0));
  const md6 = outputs.prospectiveDataset.rows[0];
  assert(Number.isFinite(md6.vector.features["home.predictedTeamShots"].value));
  const futureChanged = structuredClone(inputs);
  futureChanged.matches.forEach(match => { if (match.matchday >= 6) { match.status = "finished"; match.score = { home: 99, away: 99 }; match.teamStats = { home: { expectedGoals: 99, shots: 99 } }; } });
  const invariant = buildResearchArtifacts(futureChanged);
  assert.deepEqual(invariant.retrospectiveDataset.rows, rows);
  assert.deepEqual(invariant.prospectiveDataset.rows, outputs.prospectiveDataset.rows);
  const tampered = structuredClone(inputs); tampered.snapshotFile.snapshots[0].prediction.teamProjections[0].predictedTeamShots = 99;
  assert.throws(() => buildResearchArtifacts(tampered));
  const badManifest = structuredClone(inputs); badManifest.manifest.snapshots[0].hash = "tampered";
  assert.throws(() => buildResearchArtifacts(badManifest));
  assert.throws(() => parseConfiguration(["--prior-equivalent-matches", "0"]));
  assert.throws(() => parseConfiguration(["--unknown", "1"]));
  const packageJson = JSON.parse(fs.readFileSync(path.resolve(__dirname, "../package.json"), "utf8"));
  assert(!packageJson.scripts.build.includes("exact-score"));
  assert(!packageJson.scripts["build:predictions"].includes("exact-score"));
  return { status: "PASS", retrospective: 50, prospectivePending: 10, explicitlyConfiguredCommonSample: 28, productionBuildIntegration: false };
}

if (require.main === module) console.log(JSON.stringify({ synthetic: runSyntheticTests(), repository: runRepositoryTests() }));
module.exports = { runSyntheticTests, runRepositoryTests };
