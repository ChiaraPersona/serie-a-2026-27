import fs from 'node:fs';
import assert from 'node:assert/strict';
import {meetsMinimumPublicOdds,sharedForecastsForMatch} from '../js/pages/shared-forecast-contract.mjs';
import {createPersonalBetslipStore,PERSONAL_BETSLIP_STORAGE_KEY} from '../js/pages/personal-betslip-store.mjs';

const matchId='milan-inter-2026-27-md-10';
for(const value of [1.01,1.07,1.0799])assert.equal(meetsMinimumPublicOdds({matchId,odds:value}),false);
for(const value of [1.08,'1.08',1.09,2,null,undefined])assert.equal(meetsMinimumPublicOdds({matchId,odds:value}),true);
assert.equal(meetsMinimumPublicOdds({matchId,odds:2,betSelection:{quote:{decimal:1.07}}}),false,'Canonical price takes precedence');
assert.equal(meetsMinimumPublicOdds({matchId:'milan-inter-2026-27-md-09',odds:1.01}),true,'Previous rounds must remain unchanged');
assert.equal(meetsMinimumPublicOdds({matchId:'ucl-2026-27-md03-01',odds:1.01}),true,'Champions must remain unchanged');
assert.equal(meetsMinimumPublicOdds({matchId:'milan-inter-2026-27-md-11',odds:1.01}),true,'Do not extend this request to future rounds');
const data=JSON.parse(fs.readFileSync('data/normalized/schedina-md10.json','utf8'));
const template=sharedForecastsForMatch(data.marketCatalog,data.marketCatalog.matches[0].matchId)[0];
const context={competition:'serie-a',season:'2026-27',matchday:10};
const boundary=structuredClone({...template,context});boundary.betSelection.quote.decimal=1.08;
const low=structuredClone(boundary);low.betSelection.quote.decimal=1.07;
const memory=new Map(),storage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
let store=createPersonalBetslipStore({storage});store.setContext(context);
assert.equal(store.add(low).status,'ODDS_BELOW_PUBLIC_MINIMUM');
assert.equal(store.add(boundary).status,'ADDED');
const persisted=JSON.parse(memory.get(PERSONAL_BETSLIP_STORAGE_KEY));
persisted.contexts[persisted.activeContext].selections[0].betSelection.quote.decimal=1.07;
memory.set(PERSONAL_BETSLIP_STORAGE_KEY,JSON.stringify(persisted));
store=createPersonalBetslipStore({storage});store.setContext(context);
assert.equal(store.getSnapshot().selections.length,0,'Previously saved low price must be hidden');
store.reconcile([boundary]);
assert.equal(store.getSnapshot().selections.length,1,'A newer eligible price can restore the same contract');
const original=JSON.stringify(data);
for(const match of data.marketCatalog.matches)assert(sharedForecastsForMatch(data.marketCatalog,match.matchId).every(meetsMinimumPublicOdds));
assert.equal(JSON.stringify(data),original);
console.log('OK soglia 1.08 inclusiva: prezzi canonici, N/D, pubblicazione, aggiunte, ripristino e aggiornamento selezioni salvate; dati originali invariati.');
