const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const assert = require('assert');
const { captureSisalPage } = require('./sisal/browser-capture');
const { normalizeSisalCapture } = require('./sisal/normalize');
const { readJsonFile, writeSisalDataset } = require('./sisal/dataset-store.cjs');
const root = path.resolve(__dirname, '..');
async function main() {
  const competitionKey = 'serie-a';
  const competition = readJsonFile(path.join(root, 'data/sources/sisal-odds.json')).competitions[competitionKey];
  const fixtures = readJsonFile(path.join(root, competition.matchSource)).filter(f => f.competition === 'serie-a' && f.matchday === 11);
  assert.equal(fixtures.length, 10);
  const dateIndex = process.argv.indexOf('--date');
  const date = dateIndex >= 0 ? process.argv[dateIndex + 1] : null;
  assert(dateIndex < 0 || /^\d{4}-\d{2}-\d{2}$/.test(date || ''), '--date richiede YYYY-MM-DD');
  const scope = process.argv.indexOf('--fixtures');
  const requestedIds = scope >= 0 ? new Set(process.argv[scope + 1].split(',')) : null;
  const requestedFixtures = fixtures.filter(f => (!date || f.date === date) && f.status === 'scheduled' && (!requestedIds || requestedIds.has(f.id)));
  if (requestedIds) assert.equal(requestedFixtures.length, requestedIds.size);
  assert(requestedFixtures.length, 'Nessuna fixture da aggiornare');
  const ids = new Set(requestedFixtures.map(f => f.id));
  const target = path.join(root, 'data/normalized/odds/sisal/champions-league.json');
  const previous = readJsonFile(target);
  const retrievedAt = new Date().toISOString();
  const pageUrls = requestedFixtures.map(f => competition.eventUrlTemplate.replace('{homeTeam}',f.homeTeam).replace('{awayTeam}',f.awayTeam));
  const capture = await captureSisalPage({ pageUrls, headed: true, includeDetails: false, waitMs: 20000 });
  assert(capture.responses.length, 'Nessuna risposta Sisal');
  assert(capture.detailRequests.every(r => r.status === 200), 'Dettagli Sisal incompleti');
  const rawFile = `data/raw/odds/sisal/${competitionKey}/${retrievedAt.replace(/[:.]/g, '-')}.json.gz`;
  const artifact = { provider: 'sisal', competition: competitionKey, retrievedAt, sourceUrl: competition.url, requestedMatchday: 11, requestedFixtures: requestedFixtures.map(f => f.id), acquisition: 'public-page-browser-cdp', ...capture };
  fs.mkdirSync(path.dirname(path.join(root, rawFile)), { recursive: true });
  fs.writeFileSync(path.join(root, rawFile), zlib.gzipSync(JSON.stringify(artifact) + '\n', { level: 9 }));
  const normalized = normalizeSisalCapture({ capture: artifact, competitionKey, competition, rawFile, root });
  const updated = normalized.events.filter(e => ids.has(e.canonicalMatchId)).map(e => ({ ...e, retrievedAt, rawFile }));
  const updatedIds = new Set(updated.map(e => e.canonicalMatchId));
  assert.equal(updatedIds.size, ids.size, `Copertura MD11 incompleta: ${updatedIds.size}/${ids.size}; raw conservato, dataset invariato`);
  assert(updated.every(e => e.markets.length), 'Evento senza mercati');
  const retained = previous.events.filter(e => !updatedIds.has(e.canonicalMatchId)).map(e => ({ ...e, retrievedAt: e.retrievedAt || previous.retrievedAt, rawFile: e.rawFile || previous.rawFile }));
  const events = [...retained, ...updated];
  const markets = events.flatMap(e => e.markets);
  const matches = events.filter(e => e.eventType === 'MATCH');
  const summary = { events: events.length, matchEvents: matches.length, antepostEvents: events.length - matches.length, matchedEvents: matches.filter(e => e.canonicalMatchId).length, unmatchedEvents: matches.filter(e => !e.canonicalMatchId).length, markets: markets.length, playerMarkets: markets.filter(m => m.marketScope === 'player').length, selections: markets.reduce((n, m) => n + m.selections.length, 0) };
  writeSisalDataset(target, { ...normalized, events, summary, rawFiles: [...new Set(events.map(e => e.rawFile))] });
  console.log(JSON.stringify({ updatedFixtures: updated.length, retainedEvents: retained.length, markets: updated.reduce((n, e) => n + e.markets.length, 0), selections: updated.reduce((n, e) => n + e.markets.reduce((s, m) => s + m.selections.length, 0), 0), rawFile, summary }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
