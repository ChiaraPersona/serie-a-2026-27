import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createPersonalBetslipStore} from '../js/pages/personal-betslip-store.mjs';
const read=f=>JSON.parse(fs.readFileSync(f,'utf8'));
globalThis.officialStarterPolicy.configure(read('data/normalized/official-starter-registry.json'));
const before=read('output/md13-starter-substitute-budget/before.json').reading.marketCatalog.matches.flatMap(m=>m.selections);
const latest=read('data/normalized/reading-md13-market-catalog.json').marketCatalog.matches.flatMap(m=>m.selections);
const latestById=new Map(latest.map(s=>[s.selectionId,s]));
const old=before.find(s=>s.matchId==='inter-genoa-2026-27-md-13'&&s.catalogOrigin==='prediction-v2-player-forecast'&&s.suggestionAnalysis?.family==='shots'&&s.odds&&latestById.has(s.selectionId)&&s.individualModelProbabilityPct!==latestById.get(s.selectionId).individualModelProbabilityPct);
assert(old,'No changed saved Inter contract to verify');
const removed=before.find(s=>s.matchId==='sassuolo-napoli-2026-27-md-13'&&s.teamId==='napoli'&&s.suggestionAnalysis?.family==='shots'&&s.odds&&!latestById.has(s.selectionId));
assert(removed,'Missing unavailable Napoli contract sample');
const memory=new Map(),storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const store=createPersonalBetslipStore({storage}),context={competition:'serie-a',season:'2026-27',matchday:13};
store.setContext(context);
assert.equal(store.add({...old,context}).status,'ADDED');
assert.equal(store.add({...removed,context}).status,'ADDED');
store.reconcile(latest.map(s=>({...s,context})));
const saved=store.getSnapshot(),fresh=saved.selections.find(s=>s.selectionId===old.selectionId);
assert.equal(fresh.individualModelProbabilityPct,latestById.get(old.selectionId).individualModelProbabilityPct);
assert.equal(fresh.betSelection.evaluation.modelProbabilityPct,null,'Saved DUO received individual probability');
assert.deepEqual(fresh.betSelection.quote,old.betSelection.quote);
assert.equal(saved.selections.find(s=>s.selectionId===removed.selectionId).dataStatus,'MISSING_FROM_CURRENT_DATA');
assert(saved.assessment.issues.some(i=>i.type==='MISSING_FROM_CURRENT_DATA'&&i.severity==='blocking'));
console.log('PASS MD13 saved selections: same-contract refresh, original quote, DUO null, unavailable Napoli market blocked.');
