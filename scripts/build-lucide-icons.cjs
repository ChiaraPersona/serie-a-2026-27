// Keep the public site independent of npm/CDN availability at runtime.
const fs = require('node:fs');
const path = require('node:path');
const {icons} = require('lucide');
const names = ['ArrowRight','ArrowUpRight','ChartNoAxesCombined','Trophy','Smartphone','TrendingUp','List','Users','UserRound','RectangleVertical','Waypoints','History','ClipboardCheck','FileText','Star','Plus','ChevronDown'];
const root = path.resolve(__dirname, '..');
const nodes = Object.fromEntries(names.map(name => [name, icons[name]]));
if (Object.values(nodes).some(value => !value)) throw new Error('Unknown Lucide icon');
fs.mkdirSync(path.join(root, 'js/vendor'), {recursive:true});
fs.writeFileSync(path.join(root, 'js/vendor/lucide-icons.mjs'), '// Generated by scripts/build-lucide-icons.cjs; Lucide ISC license in lucide-LICENSE.txt.\nexport default '+JSON.stringify(nodes)+';\n');
fs.copyFileSync(path.join(root, 'node_modules/lucide/LICENSE'), path.join(root, 'js/vendor/lucide-LICENSE.txt'));
